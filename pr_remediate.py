def _promotion_evidence_is_actionable(rec) -> bool:
    """Is there something on the review record that editing a promotion branch could fix?

    Consulted only when pr_auto_remediate_skip_promotion is off, i.e. when the
    operator has deliberately allowed promotion PRs to be repaired in place so a
    denied promotion cannot stall the unattended chain. It answers the narrower
    question that permission was actually granted for: did the panel name a
    defect, or is it merely unsure?

    Actionable means a stated objection:
      * any seat returning a verdict other than Approve, or
      * an in-repo Tier-1 finding.

    Cross-repo twin findings are excluded on the same reasoning should_remediate
    uses — the fix engine only rewrites files in this PR's own checkout, so no
    diff it can produce will ever clear one.

    A bare confidence deficit is deliberately NOT actionable. It describes the
    reviewers, not the diff, and the diff on a promotion branch is by definition
    code that was already reviewed and merged on the source branch.
    """
    # No review record: nothing to act on.
    if not rec:
        return False
    # Any reviewer seat that did not approve is a stated objection.
    for verdict in (rec.get("panel_verdict"), rec.get("panel2_verdict")):
        if verdict is not None and str(verdict).strip().lower() != "approve":
            return True
    # Read the finding counts; unreadable counts mean nothing actionable.
    try:
        errors = int(rec.get("errors") or 0)
        warnings = int(rec.get("warnings") or 0)
        external = int(rec.get("tier1_external") or 0)
    except (TypeError, ValueError):
        return False
    # In-repo errors, or more warnings than the cross-repo ones, are actionable.
    return errors > 0 or warnings > external

# Boundaries that block automated remediation when the diff really touches them.
TARGET_GUARDRAIL_BOUNDARIES = {
    "psk-hardcode",
    "transport-scheme",
    "rbac-model",
    "state-encryption",
    "auth-onboarding",
    "self-update",
}

# Dangerous patterns looked for in added lines: reverse shells, curl|sh, eval of base64,
# TLS verification turned off, and hardcoded pre-shared keys.
REVERSE_SHELL_RE = re.compile(
    r"(?i)(?:nc(?:\.traditional)?\s+-[el]|/bin/(?:ba)?sh\s+-i|bash\s+-i\s+>&|pty\.spawn|socket\.connect\s*\(\s*\(\s*['\"][0-9.]+|socat\s+exec:)"
)
PIPED_SHELL_RE = re.compile(
    r"(?i)(?:curl\s+-[^\n]*\|\s*(?:ba)?sh|wget\s+-[^\n]*\|\s*(?:ba)?sh)"
)
DYNAMIC_EXEC_RE = re.compile(
    r"(?i)(?:exec\s*\(\s*base64\.b64decode|eval\s*\(\s*base64\.b64decode|marshal\.loads\b)"
)
TLS_VERIFY_BYPASS_RE = re.compile(
    r"(?i)(?:ssl_verify\s*=\s*False|check_hostname\s*=\s*False|CERT_NONE|\bverify\s*=\s*False\b)"
)
PSK_HARDCODE_RE = re.compile(
    r"(?i)\b(?:psk|pre[-_]?shared[-_]?key|shared[-_]?secret)\b\s*[:=]\s*['\"][^'\"]+['\"]"
)


def _extract_added_lines(raw_patch: str) -> str:
    """Extract only added diff lines from unified diff patch, or fallback to raw string."""
    # Empty patch: nothing added.
    if not raw_patch:
        return ""
    # A real diff: keep only "+" lines (minus the "+++" header), without the "+".
    lines = raw_patch.splitlines()
    has_diff_markers = any(l.startswith("+") for l in lines if not l.startswith("+++"))
    if has_diff_markers:
        added = [l[1:] for l in lines if l.startswith("+") and not l.startswith("+++")]
        return "\n".join(added)
    # Not a diff: use the text as-is.
    return raw_patch


def _boundary_content_corroborated(boundary, files) -> bool:
    """Does the diff's ADDED content actually corroborate a path-matched boundary?

    A path glob alone (e.g. psk-hardcode's ``**/security/**``) proves only that a
    PR touched a sensitive DIRECTORY — not that it did the dangerous THING. Path
    matching alone is right for the auto-MERGE deny-list (where the cost of being
    wrong is an unattended merge), but using it to gate REMEDIATION meant every
    ordinary change under a ``security/`` directory was permanently locked out of
    automated repair: lm#1018 was refused with "Diff touches protected
    architectural boundary: psk-hardcode" for a diff that hardcoded nothing.

    So a path hit is now necessary but not sufficient: the added lines must also
    carry the boundary's own keywords, or trip the precise content regex this
    module already defines for it. Fails closed in every ambiguous case (no
    readable patch, no keywords to test), and pr_review._automerge_decision's
    boundary deny-list is deliberately NOT changed by any of this.
    """
    # Gather the added lines from all files; none readable means fail closed (corroborated).
    added = "\n".join(_extract_added_lines(getattr(f, "patch", None) or "") for f in (files or []))
    if not added.strip():
        return True
    added_cf = added.lower()

    # Boundaries with a precise regex: a hit corroborates.
    bid = (boundary.get("id") or "").strip().lower()
    if bid == "psk-hardcode" and PSK_HARDCODE_RE.search(added):
        return True
    if bid == "transport-scheme" and TLS_VERIFY_BYPASS_RE.search(added):
        return True

    # Otherwise look for the boundary's keywords; no keywords means fail closed.
    keywords = [str(k).strip().lower() for k in (boundary.get("keywords") or []) if str(k).strip()]
    if not keywords:
        return True
    return any(k in added_cf for k in keywords)


def check_pr_guardrails(
    pr: Any,
    files: Optional[List[Any]] = None,
    changed_paths: Optional[List[str]] = None,
    config: Optional[Dict[str, Any]] = None,
) -> Tuple[bool, Optional[str]]:
    """Deterministic security and architectural boundary pre-checks for automated PR remediation.

    Checks:
      1. Deterministic boundary matching against DEFAULT_BOUNDARIES (psk-hardcode,
         transport-scheme, rbac-model, state-encryption, auth-onboarding, self-update).
      2. Credential checks using secrets_scan.check_secrets(files) (level == "error").
      3. Patch inspection of added diff lines for reverse shells, piped downloaders,
         dynamic eval/exec, and TLS verify bypass in security/agent/spoke/transport paths.

    Returns:
      (True, None) if clean.
      (False, violation_reason) if any guardrail is violated.
    """
    # Work out the changed paths, from the file list if not given.
    config = config or {}
    paths = list(changed_paths or [])
    if not paths and files:
        paths = [getattr(f, "filename", "") for f in files if getattr(f, "filename", "")]

    # 0. Extended fleet invariants check
    fleet_ok, fleet_violation = fleet_guardrails.check_fleet_invariants(pr, files, paths)
    if not fleet_ok:
        return False, fleet_violation

    # 1. Deterministic boundary checks against target DEFAULT_BOUNDARIES
    # Use the configured boundaries if set, else the shipped defaults, limited to ours.
    all_boundaries = (
        config.get("feature_boundaries")
        if isinstance(config.get("feature_boundaries"), list) and config.get("feature_boundaries")
        else getattr(feature_boundary, "DEFAULT_BOUNDARIES", [])
    )
    guardrail_boundaries = [
        b for b in all_boundaries
        if b.get("id") in TARGET_GUARDRAIL_BOUNDARIES
    ]
    hits = feature_boundary.boundary_hits(paths, guardrail_boundaries)
    # A path hit is necessary but NOT sufficient — see _boundary_content_corroborated.
    corroborated = [h for h in hits if _boundary_content_corroborated(h, files)]
    if corroborated:
        ids = ", ".join(h.get("id", "?") for h in corroborated)
        return False, f"Diff touches protected architectural boundary: {ids}"
    if hits:
        logger.info(
            "check_pr_guardrails: boundary path hit(s) %s not corroborated by the diff's "
            "added lines — allowing remediation",
            ", ".join(h.get("id", "?") for h in hits))

    # 2. Credential checks using secrets_scan.check_secrets(files)
    # Any error-level secret finding blocks remediation; a scanner failure is only logged.
    if files:
        try:
            findings = secrets_scan.check_secrets(files)
            error_findings = [f for f in findings if f.get("level") == "error"]
            if error_findings:
                first = error_findings[0]
                title = first.get("title") or "Hardcoded secret detected"
                return False, f"Credential check violation: {title}"
        except Exception as e:
            logger.warning("check_pr_guardrails: secrets_scan encountered error: %s", e)

    # 3. Patch inspection of added diff lines
    # Check each file's added lines for dangerous patterns.
    for f in (files or []):
        filename = getattr(f, "filename", "") or ""
        raw_patch = getattr(f, "patch", None)
        if not raw_patch:
            continue
        patch = _extract_added_lines(raw_patch)

        # Reverse shell check
        if REVERSE_SHELL_RE.search(patch):
            return False, f"Security guardrail violation: reverse shell pattern detected in `{filename}`"

        # Piped shell downloader check
        if PIPED_SHELL_RE.search(patch):
            return False, f"Security guardrail violation: piped shell downloader detected in `{filename}`"

        # Dynamic eval/exec check
        if DYNAMIC_EXEC_RE.search(patch):
            return False, f"Security guardrail violation: dynamic code execution pattern detected in `{filename}`"

        # Direct PSK / shared secret pattern check in patch
        if PSK_HARDCODE_RE.search(patch):
            return False, f"Security guardrail violation: hardcoded PSK or shared secret detected in `{filename}`"

        # TLS verify bypass check in sensitive paths
        fn_lower = filename.lower()
        is_sensitive_path = any(term in fn_lower for term in ("security", "agent", "spoke", "transport"))
        has_sensitive_context = is_sensitive_path or any(
            any(term in p.lower() for term in ("security", "agent", "spoke", "transport"))
            for p in paths
        )
        if has_sensitive_context and TLS_VERIFY_BYPASS_RE.search(patch):
            return False, f"Security guardrail violation: TLS verification bypass in sensitive path `{filename}`"

    # Every check passed.
    return True, None


def assess_fix_complexity(
    critique: Optional[str] = "",
    dissent_feedback: Optional[str] = "",
    findings: Optional[List[Dict[str, Any]]] = None,
    files: Optional[List[Any]] = None,
    confidence: Optional[float] = None,
) -> str:
    """Assess the complexity tier required for PR auto-remediation.

    - Low / small complexity ("small"):
      Findings are only tooltips/lint/docs, or critique text contains "minor", "nit",
      "formatting", "typo", "docstring", "comment", or single-file change with
      confidence >= 0.85 and no "reject"/"deny".
    - Medium complexity ("medium"):
      Critique or dissent mentions "control-flow", "pagination", "caching", "parsing",
      "exception", "regex", "status", "enum", or 1-3 files touched with confidence
      between 0.60 and 0.85.
    - Large / frontier complexity ("large"):
      Critique or dissent mentions "concurrency", "race condition", "deadlock",
      "state conflation", "reachability", "refactor", or confidence < 0.60 or explicit
      "reject"/"deny", or > 3 files modified.
    """
    # Combine the critique and dissent into one lowercase text to search.
    critique_str = critique or ""
    dissent_str = dissent_feedback or ""
    text = f"{critique_str}\n{dissent_str}".lower()

    # No confidence given: try to read one ("confidence: 0.7" or "80%") from the text.
    if confidence is None:
        conf_match = re.search(r"(?i)(?:confidence|score)[:\s]+(0\.\d+|\d+%)", text)
        if conf_match:
            raw_c = conf_match.group(1)
            if raw_c.endswith("%"):
                confidence = float(raw_c[:-1]) / 100.0
            else:
                confidence = float(raw_c)

    # How many files the change touches.
    file_count = len(files) if files is not None else 0

    # Large / frontier complexity
    large_keywords = ("concurrency", "race condition", "deadlock", "state conflation", "reachability", "refactor")
    has_large_kw = any(kw in text for kw in large_keywords)
    has_reject_deny = bool(re.search(r"\b(reject|deny)\b", text))
    low_conf = (confidence is not None and confidence < 0.60)
    many_files = file_count > 3

    if has_large_kw or has_reject_deny or low_conf or many_files:
        return "large"

    # Medium complexity
    medium_keywords = ("control-flow", "pagination", "caching", "parsing", "exception", "regex", "status", "enum")
    has_medium_kw = any(kw in text for kw in medium_keywords)
    med_conf = (confidence is not None and 0.60 <= confidence < 0.85 and 1 <= file_count <= 3)

    if has_medium_kw or med_conf:
        return "medium"

    # Small complexity
    small_keywords = ("minor", "nit", "formatting", "typo", "docstring", "comment")
    has_small_kw = any(kw in text for kw in small_keywords)

    findings_only_minor = False
    if findings:
        minor_terms = ("tooltip", "lint", "doc", "docstring", "comment", "formatting", "typo")
        findings_only_minor = all(
            any(term in (f.get("title", "") + " " + f.get("detail", "")).lower() for term in minor_terms)
            for f in findings
        )

    single_file_high_conf = (file_count == 1 and (confidence is not None and confidence >= 0.85))

    if findings_only_minor or has_small_kw or single_file_high_conf:
        return "small"

    if file_count > 1:
        return "medium"
    return "small"


DEFAULT_TARGET_SCORE = 0.95  # "as close to 100% as possible", in practice


def _clears_merge_bar(rec, config):
    """Does this PR ALREADY satisfy the auto-merge gate?

    Mirrors pr_review._maybe_auto_merge's verdict/confidence criteria exactly
    so remediation can stop once a PR is good enough to MERGE, rather than
    chasing the (higher) remediation target forever.

    This exists because the two bars are deliberately different — the merge
    threshold (feature_automerge_min_confidence, e.g. 0.90) sits BELOW the
    remediation target (pr_remediate_target_score, 0.95) — and that gap was a
    livelock: a PR at 0.91 is merge-eligible, but remediation fired anyway to
    chase 0.95, and every remediation PUSHES A COMMIT. The new head invalidated
    the panel results the merge decision depends on ("no pre-review record for
    the current head yet"), so the merge was deferred to a re-review that
    scored ~0.91 again and remediated again. Merge-eligible PRs were therefore
    never merged; they burned the attempt budget and, worse, sometimes
    REGRESSED an Approve into a Reject and landed in exhausted_human_review —
    which is exactly the pile of PRs an operator then has to approve by hand.

    Returns (clears: bool, threshold: float). The threshold is always returned,
    even when `clears` is False, so callers can report the bar that was missed.

    Pure function — no I/O. Never raises.

    NOTE: the default threshold is 1.0 ("auto-merge off"), so on a fleet that
    has not enabled auto-merge nothing clears and remediation behaves exactly
    as it did before. This gate only ever engages where an operator has set an
    explicit bar. `or 1.0` is deliberately NOT used when reading the config: a
    legitimate threshold of 0.0 is falsy and would be silently rewritten to 1.0.
    """
    # Read the merge threshold (default 1.0 = auto-merge off), clamped to 0-1.
    raw = config.get("feature_automerge_min_confidence")
    try:
        threshold = 1.0 if raw is None else float(raw)
    except (TypeError, ValueError):
        threshold = 1.0
    threshold = max(0.0, min(1.0, threshold))

    # No review record: nothing clears.
    if not rec:
        return False, threshold

    # Both panels must have run, approved, and met the threshold.
    for status_key, verdict_key, conf_key in (
        ("panel_status", "panel_verdict", "panel_confidence"),
        ("panel2_status", "panel2_verdict", "panel2_confidence"),
    ):
        # A panel that could not RUN has not approved anything.
        if rec.get(status_key):
            return False, threshold
        if rec.get(verdict_key) != "Approve":
            return False, threshold
        conf = rec.get(conf_key)
        if conf is None:
            return False, threshold
        try:
            conf = float(conf)
        except (TypeError, ValueError):
            return False, threshold
        if conf < threshold:
            return False, threshold

    # Both panels clear the bar.
    return True, threshold


def should_remediate(rec, config):
    """THE SINGLE CHOKE POINT that defines AppBuilder's remediation OBJECTIVE.

    AppBuilder's job on a PR is not merely to publish an opinion — it is to
    drive that PR's skeptical-panel approval score as close to 100% as it can
    get it, unattended. This function states that objective in one place so it
    is explicit, auditable and testable, instead of being implied by whatever
    fix_one_pr happens to bail out on.

    Before this existed there was NO verdict-driven trigger at all: remediation
    was attempted on every open PR on every scan and then silently no-opped
    inside fix_one_pr ("No findings to fix"), which posts nothing and records
    nothing. A panel could return a detailed DENY (see lm#1019: both panels
    🔴 DENY, auto-merge held) and AppBuilder would leave no trace that it had
    even considered repairing it, so the operator had to click Fix by hand.

    Pure function — no I/O, no side effects, no state writes.

    rec:    state["pr_reviews"]["repo#num"] — panel_*/panel2_*/errors/warnings.
    config: live config; "pr_remediate_target_score" (default 0.95) is the bar
            a PR must clear before AppBuilder stops trying to improve it.

    Returns (should: bool, reason: str, deficit: float) where `deficit` is how
    far below target the PR currently sits (0.0 when it already clears).
    """
    # No review record: nothing to act on.
    if not rec:
        return False, "no review record yet", 0.0

    # Each panel's status (set when it failed to run).
    panel_status = rec.get("panel_status")
    panel2_status = rec.get("panel2_status")

    # A panel's verdict is USABLE only when it actually produced one AND did not
    # error. The previous guard bailed out whenever EITHER panel carried a
    # status, which collapsed four distinct states into one "nothing to act on"
    # answer: both ran, both failed, panel 1 ran while panel 2 errored, and vice
    # versa. In the mixed cases there IS a recommendation on the table — a full
    # DENY from the panel that ran — and remediation was silently suppressed for
    # it, which is precisely the failure this function exists to eliminate.
    # Bail out only when NO panel produced a usable verdict.
    panels = (
        (rec.get("panel_verdict"), panel_status, rec.get("panel_confidence")),
        (rec.get("panel2_verdict"), panel2_status, rec.get("panel2_confidence")),
    )
    # Collect the verdicts (and confidences) of panels that actually ran.
    verdicts = []
    confs = []
    for verdict, status, confidence in panels:
        if verdict is None or status:
            continue
        verdicts.append(verdict)
        # Confidence counts only when it belongs to a panel whose verdict we
        # are actually using — carried alongside the verdict rather than looked
        # up afterwards, so the two can never be attributed to the wrong panel.
        if confidence is not None:
            try:
                confs.append(float(confidence))
            except (TypeError, ValueError):
                pass

    if not verdicts:
        status = panel_status or panel2_status
        if status:
            # A panel that could not RUN produced no recommendation to act on.
            # Regenerating a fix against an outage burns tokens and moves the
            # head SHA for nothing; pr_review's own retry path re-runs the panel.
            return False, "panel could not run (%s) — nothing to act on" % status, 0.0
        return False, "no panel verdict recorded", 0.0

    # Read the target score (default 0.95), clamped to 0-1.
    try:
        target = float(config.get("pr_remediate_target_score", DEFAULT_TARGET_SCORE))
    except (TypeError, ValueError):
        target = DEFAULT_TARGET_SCORE
    target = max(0.0, min(1.0, target))

    # "No confidence was reported" is NOT "confidence 0%". Scoring an absent
    # metric as zero made the deficit the full target, which forced the largest
    # (most expensive) remediation tier and made an Approve-with-no-number look
    # maximally deficient. Unknown stays unknown: score is None and the
    # confidence-driven branches below simply do not fire.
    if confs:
        score = min(confs)
        deficit = round(max(0.0, target - score), 4)
    else:
        score = None
        deficit = 0.0

    # TIER-1 FINDINGS BLOCK THE MERGE GATE, SO THEY MUST BE CHECKED FIRST.
    # This sits above the merge-bar early return on purpose. pr_review refuses
    # to auto-merge while any Tier-1 error or warning is on the record, but the
    # early return below declines to remediate as soon as the panel score
    # clears the merge bar — on the premise that the PR "already IS fit to
    # merge". With findings present that premise is simply false, and the two
    # gates deadlock: remediation says "just merge it", the merge gate says
    # "not while findings are open", and the PR is held forever having never
    # been repaired. That is not the bounded delay the docstring below promises
    # -- it is a permanent stall, and it is what stranded an Approve/Approve PR
    # across three consecutive scans. Remediating is the only exit, and it
    # terminates: once the findings are cleared this branch stops firing and
    # the merge-bar return takes over.
    errors = int(rec.get("errors") or 0)
    warnings = int(rec.get("warnings") or 0)
    # EXTERNAL TIER-1 FINDINGS ARE NOT REMEDIABLE HERE, AT ALL.
    # A cross-repo twin finding says "the copy of this file in the OTHER repo is
    # out of lockstep". The fix engine only rewrites files in this PR's own
    # checkout, so no diff it can produce will ever clear one. Left in the count
    # above, they read as ordinary repairable work: lm#1058 sat on five of them,
    # burned all three attempts generating diffs the panel then correctly
    # rejected for "not addressing the actual blocking findings", and ended
    # stamped "Automated Remediation Limit Reached — manual operator
    # intervention required" — which points the operator at the wrong PR
    # entirely. The real action is to open one in the twin repo.
    #
    # This does NOT unblock the merge: pr_review still holds the PR while any
    # Tier-1 finding stands, which is correct because the drift is real. It only
    # stops spending the (expensive, model-backed) attempt budget on something
    # structurally impossible, so the budget is still intact for the in-repo
    # findings of a LATER head. Mixed records therefore still remediate: the
    # skip applies only when EVERY Tier-1 finding is external.
    # Cross-repo twin findings counted separately; if they are all there is, skip.
    external = int(rec.get("tier1_external") or 0)
    if errors == 0 and 0 < warnings <= external:
        return (False,
                "%d Tier-1 finding(s) are cross-repo twin obligations — no edit to this PR "
                "can clear them; open the matching PR in the twin repo" % warnings,
                0.0)
    if errors > 0 or warnings > 0:
        # Findings short-circuit the branches below, so the severity FLOORS those
        # branches would have applied have to be applied here too — otherwise a
        # DENY-plus-findings record (or one with no confidence reported at all)
        # would return the raw, possibly 0.0, deficit and be remediated at the
        # cheapest model tier, collapsing three distinct severities into one.
        # Start from the confidence deficit, then apply the severity floors below.
        findings_deficit = deficit
        # Any non-Approve verdict means the full target is missing.
        if any(str(v).strip().lower() != "approve" for v in verdicts):
            findings_deficit = max(findings_deficit, target)
        elif config.get("pr_remediate_address_all_concerns", True):
            # Dissenting or unrated reviewers count as half the target missing.
            dissents = int(rec.get("panel_dissents") or 0) + int(rec.get("panel2_dissents") or 0)
            unrated = int(rec.get("panel_unrated") or 0) + int(rec.get("panel2_unrated") or 0)
            if dissents or unrated:
                findings_deficit = max(findings_deficit, round(target / 2.0, 4))
            else:
                # Otherwise use the lowest individual reviewer confidence, if reported.
                reviewer_confs = [c for c in (rec.get("panel_min_reviewer_confidence"),
                                              rec.get("panel2_min_reviewer_confidence"))
                                  if c is not None]
                if reviewer_confs:
                    try:
                        worst = min(float(c) for c in reviewer_confs)
                    except (TypeError, ValueError):
                        worst = None
                    if worst is not None and worst < target:
                        findings_deficit = max(findings_deficit,
                                               round(max(0.0, target - worst), 4))
        return (True, "Tier-1 findings present (%d error(s), %d warning(s))" % (errors, warnings),
                findings_deficit)

    # MERGE-ELIGIBLE PRs ARE DONE. Remediation's purpose is to get a PR fit to
    # merge; once it already IS fit to merge, continuing to "improve" it is not
    # free — every attempt pushes a commit, which moves the head, which
    # invalidates the very panel results the merge decision reads. That is a
    # livelock, not a refinement: the PR is re-reviewed, scores about the same,
    # is remediated again, and never merges. Stop here and let it merge.
    # (See _clears_merge_bar: with auto-merge off this never fires.)
    _clears, _merge_bar = _clears_merge_bar(rec, config)
    if _clears:
        return (False,
                "panel score %s already clears the %.2f auto-merge bar — merging beats "
                "chasing the %.2f target (further fixes would invalidate the review)"
                % ("%.2f" % score if score is not None else "n/a", _merge_bar, target),
                0.0)

    # A non-Approve verdict is the strongest possible signal and is NOT
    # redeemable by a high confidence number: a reviewer that is 85% sure the
    # PR is wrong is a 0% approval, not an 85% one. Floor the deficit at the
    # full target so the model tiering in assess_fix_complexity/
    # next_remediation_requirements treats it as the large job it is.
    for v in verdicts:
        if str(v).strip().lower() != "approve":
            return (True,
                    "panel verdict %r is below Approve — remediating toward the %.0f%% target"
                    % (v, target * 100),
                    max(deficit, target))

    # Approved but scored below target: remediate.
    if score is not None and score < target:
        return True, "panel score %.2f is below the %.2f target" % (score, target), deficit

    # Every panel says Approve and the aggregate score clears the bar — but an
    # aggregate hides dissent. A panel of two that returns "Approve · 91%" can
    # contain one reviewer who rejected outright, and AppBuilder used to merge
    # straight over the top of that objection because only the aggregate was
    # ever consulted. If ANY individual reviewer withheld approval, or rated the
    # change below target, there is still a concern on the table and the PR is
    # not yet as close to 100% as it can be.
    if config.get("pr_remediate_address_all_concerns", True):
        # Any individual reviewer who did not approve keeps the concern open.
        dissents = int(rec.get("panel_dissents") or 0) + int(rec.get("panel2_dissents") or 0)
        if dissents:
            return (True,
                    "%d individual reviewer(s) did not approve despite the panel verdict — "
                    "addressing their concerns before merging" % dissents,
                    max(deficit, round(target / 2.0, 4)))
        # So does any reviewer whose own confidence is below target.
        reviewer_confs = [c for c in (rec.get("panel_min_reviewer_confidence"),
                                      rec.get("panel2_min_reviewer_confidence")) if c is not None]
        if reviewer_confs and min(reviewer_confs) < target:
            worst = min(reviewer_confs)
            return (True,
                    "lowest individual reviewer confidence %.2f is below the %.2f target"
                    % (worst, target),
                    round(max(0.0, target - worst), 4))

        # A seat that returned no usable verdict is not a seat that approved.
        # The per-reviewer counts were persisted but never consulted, so a panel
        # where one reviewer failed and one approved cleared this branch exactly
        # as if it had been unanimous — "we could not see whether a reviewer
        # dissented" being read as "no reviewer dissented" is the merge-over-an-
        # objection bug this branch exists to prevent.
        unrated = int(rec.get("panel_unrated") or 0) + int(rec.get("panel2_unrated") or 0)
        if unrated:
            return (True,
                    "%d reviewer seat(s) produced no usable verdict — unanimity cannot be "
                    "confirmed, so the concern is treated as still open" % unrated,
                    max(deficit, round(target / 2.0, 4)))

    # (The Tier-1 findings check that used to live here now runs above the
    # merge-bar early return — see the comment there for why the order matters.)

    # Approved with no score to improve on.
    if score is None:
        return (False,
                "panel verdict(s) Approve; no confidence reported — nothing further to act on",
                0.0)

    return False, "panel score %.2f already meets the %.2f target" % (score, target), 0.0


def remediation_pending(rec, config):
    """The "improve before merging" gate.

    AppBuilder's objective is to get a PR as close to 100% panel approval as it
    can BEFORE merging it, so merging a PR that AppBuilder was about to improve
    defeats the purpose — and that is exactly what happened, because the merge
    threshold (feature_automerge_min_confidence) sits below the remediation
    target (pr_remediate_target_score).

    That gap cuts BOTH ways, though, and the opposite failure is worse. A PR
    sitting between the two bars is already merge-eligible, and remediating it
    pushes a commit that invalidates the panel results the merge gate reads —
    so it never merged at all. should_remediate now stops at the merge bar (see
    _clears_merge_bar), which is what makes the guarantee below hold in
    practice and not just on paper.

    Every "stop trying" condition — guardrail block, exhausted attempts, kill
    switch, target already met, already merge-eligible — returns False, so this
    can only ever delay a merge by a bounded number of remediation attempts and
    can never deadlock a PR.
    """
    # Every "stop trying" condition returns False.
    if not rec:
        return False, "no review record"
    if not config.get("pr_auto_remediate_enabled", True):
        return False, "auto-remediation is off"
    if rec.get("auto_remediate_blocked"):
        return False, "remediation is blocked by a guardrail"
    if rec.get("auto_remediate_status") == "exhausted_human_review":
        return False, "remediation attempts exhausted"

    # Read the attempts so far and the maximum allowed.
    try:
        attempts = int(rec.get("remediation_attempts") or 0)
    except (TypeError, ValueError):
        attempts = 0
    try:
        max_attempts = int(config.get("pr_auto_remediate_max_attempts", 3))
    except (TypeError, ValueError):
        max_attempts = 3

    # Out of attempts: only the premium turn, if still unused, keeps going.
    if attempts >= max_attempts:
        if not premium_turn_available(rec, config):
            return False, "remediation attempts exhausted (%d/%d)" % (attempts, max_attempts)

    # Otherwise the remediation objective decides.
    should, reason, _deficit = should_remediate(rec, config)
    return (True, reason) if should else (False, reason)


def _premium_budget(config):
    """How many remediation attempts a single PR may spend on the premium
    escalation models (fable / astra). Default 1 -- these are the most
    expensive models on the roster, so the cap is a COUNT, not merely a
    position in the ladder. Clamped to 0..3; 0 disables the tier."""
    # Read the setting (default 1) and clamp it to 0-3.
    try:
        n = int((config or {}).get("pr_remediate_premium_attempts", 1))
    except (TypeError, ValueError):
        n = 1
    return max(0, min(n, 3))


def premium_turn_available(rec, config):
    """True when the ordinary remediation budget is spent but this PR still
    has an unused premium escalation attempt.

    This grants the premium turn IN ADDITION to
    `pr_auto_remediate_max_attempts` rather than inside it: the premium tier
    exists to escalate a PR the ordinary ladder has already failed, so
    carving its attempt out of that same budget would just replace the
    Opus-class last turn instead of following it."""
    # No record, or the premium tier disabled: no premium turn.
    if not rec:
        return False
    if _premium_budget(config) <= 0:
        return False
    # Compare premium attempts used against the budget.
    try:
        used = int(rec.get("premium_attempts") or 0)
    except (TypeError, ValueError):
        used = 0
    return used < _premium_budget(config)


def next_remediation_requirements(
    prev_reqs: Any,
    failure_kind: Optional[str] = None,
    tried_key: Optional[str] = None,
    config: Optional[Dict[str, Any]] = None,
    attempts: int = 0,
    premium: bool = False,
) -> Any:
    """Step up model complexity tier and exclude tried model on remediation failure.

    After `attempts` failed turns the pool is additionally narrowed to
    Opus-class models (fix_engine._last_turn_fix_exclusions). Raising the
    complexity tier alone is a no-op at the top of the ladder -- every
    allowlisted model already clears "large" -- so without this narrowing the
    picker just re-seats the same cheapest-capable model that already failed.

    `premium` selects the final rung: the pool is narrowed to the premium
    escalation models instead. On every other turn those models are excluded
    outright, because Copilot's generic registry fallback rates unmatched
    models "cheap" and the cost-first picker would otherwise spend the most
    expensive models on the roster on routine first attempts.
    """
    # Start from the previous exclusions plus the model that just failed.
    exclude = set(getattr(prev_reqs, "exclude_models", ()) or ())
    if tried_key:
        exclude.add(tried_key)

    # Cost guard FIRST, so it applies no matter which branch below runs.
    try:
        import fix_engine
        exclude = set(fix_engine._premium_fix_exclusions(
            config or {}, existing=tuple(sorted(exclude, key=str)),
            want_premium=bool(premium)))
        if premium:
            logger.info("remediation turn %d: PREMIUM escalation — narrowing the fix pool to "
                        "the reserved models (one attempt per PR)", attempts + 1)
    except Exception as e:  # noqa: BLE001 -- a broken import must not stop the retry
        logger.debug("next_remediation_requirements: premium pool split skipped: %s", e)

    # After this many failed turns, narrow to Opus-class models (default 2).
    try:
        threshold = int((config or {}).get("pr_remediate_last_turn_after_attempts", 2))
    except (TypeError, ValueError):
        threshold = 2

    # Not a premium turn and past the threshold: try narrowing to Opus-class models.
    if not premium and threshold > 0 and attempts >= threshold:
        try:
            import fix_engine
            before = set(exclude)
            exclude = set(fix_engine._last_turn_fix_exclusions(
                config or {}, existing=tuple(sorted(exclude, key=str))))
            if exclude != before:
                logger.info("remediation turn %d: narrowing the fix pool to Opus-class models "
                            "after %d failed attempt(s)", attempts + 1, attempts)
            else:
                logger.info("remediation turn %d: Opus-class escalation was a no-op (disabled, "
                            "enumeration failed, or no selectable Opus model) -- ordinary retry",
                            attempts + 1)
        except Exception as e:  # noqa: BLE001 -- escalation is best-effort; a broken
                                # import must not stop the retry from happening at all.
            logger.debug("next_remediation_requirements: Opus-class escalation skipped: %s", e)

    # Step the complexity up one level (capped at the top).
    complexity = getattr(prev_reqs, "complexity", "small")
    try:
        idx = _COMPLEXITY_RANK_ORDER.index(complexity)
    except ValueError:
        idx = 1
    next_complexity = _COMPLEXITY_RANK_ORDER[min(idx + 1, len(_COMPLEXITY_RANK_ORDER) - 1)]

    # Build the new requirements, keeping the other settings from the previous ones.
    from model_selection import LlmRequirements as _ReqClass
    return _ReqClass(
        complexity=next_complexity,
        needs_structured_output=getattr(prev_reqs, "needs_structured_output", True),
        min_context_tokens=getattr(prev_reqs, "min_context_tokens", 0),
        restrict=getattr(prev_reqs, "restrict", None),
        must_escalate_to_human=getattr(prev_reqs, "must_escalate_to_human", False),
        # sorted(key=str): exclude sets legitimately MIX types -- callers pass model-name
        # strings (what the review records persist) while _enumerate_candidates yields
        # ModelKey tuples, and a bare sorted() over both raises TypeError, which surfaced
        # as an unfixable "'<' not supported between str and tuple" on every PR.
        exclude_models=tuple(sorted(exclude, key=str)),
    )


def auto_remediate_pr(
    gh: Any,
    repo: Any,
    pr: Any,
    config: Optional[Dict[str, Any]] = None,
    fix_fn: Optional[Any] = None,
    deficit: float = 0.0,
) -> Tuple[bool, str]:
    """Execute automated closed-loop remediation for an open PR with review findings.

    `deficit` is how far below the approval target should_remediate judged this
    PR to be; it floors the complexity tier so a flat-out DENY is not handed to
    a "small" model just because the diff happens to be one file.
    """
    # Identify the PR and get (or create) its review record.
    config = config or {}
    repo_full_name = getattr(repo, "full_name", str(repo))
    key = f"{repo_full_name}#{pr.number}"

    if "pr_reviews" not in state:
        state["pr_reviews"] = {}
    if key not in state["pr_reviews"]:
        state["pr_reviews"][key] = {}
    rec = state["pr_reviews"][key]

    # The PR's changed files, their paths, and the current head commit.
    files = list(pr.get_files())
    changed_paths = [getattr(f, "filename", "") for f in files if getattr(f, "filename", "")]
    head_sha = getattr(getattr(pr, "head", None), "sha", None)

    def _post_once(marker: str, body: str, **fields) -> None:
        """Post a notice at most ONCE per (marker, head) pair.

        The scan re-runs every poll cycle, and both the guardrail banner and the
        attempt-ceiling banner used to be posted unconditionally — lm#1018
        collected the same multi-hundred-word guardrail banner twice inside
        eighteen seconds. Mirror the "record it once, stay quiet until the
        reason actually changes" guard pr_review._maybe_auto_merge already uses.
        """
        # A stamp of this notice and head; post only if it differs from the last one.
        stamp = "%s@%s" % (marker, head_sha or "?")
        if rec.get("auto_remediate_notice") != stamp:
            try:
                pr.create_issue_comment(body)
            except Exception as e:  # noqa: BLE001
                logger.warning("auto_remediate_pr: failed to post %s comment on %s: %s",
                               marker, key, e)
            # Remember the stamp and save the record either way.
            fields["auto_remediate_notice"] = stamp
        update_pr_review(repo_full_name, pr.number, **fields)

    # Never rewrite a promotion/backmerge PR — see _PROMOTION_HEAD_RE.
    head_ref = getattr(getattr(pr, "head", None), "ref", "") or ""
    if _PROMOTION_HEAD_RE.match(head_ref):
        # Skip promotion PRs unless explicitly allowed, and even then only with a real objection.
        reason = ""
        if config.get("pr_auto_remediate_skip_promotion", True):
            reason = (
                "promotion PR (head '%s') — remediation skipped so the branch keeps "
                "exactly what the source branch has" % head_ref
            )
        elif not _promotion_evidence_is_actionable(rec):
            # FLAG-OFF IS NOT A LICENCE TO EDIT A PROMOTION BRANCH FOR NO STATED
            # REASON. Turning pr_auto_remediate_skip_promotion off is a supported
            # configuration (docs/ab.md) whose entire purpose is narrow: a panel
            # that DENIES a promotion, or files a Tier-1 finding against it, must
            # be repairable in place rather than stalling the unattended chain.
            # backmerge.yml then returns that repair to the source branch, which
            # is what keeps the edit from being orphaned.
            #
            # A soft confidence number is not such a reason. lm#1063 was reviewed
            # "0 findings", every seat Approve, and scored 0.69 against the 0.95
            # target — so the score branch of should_remediate fired and the fix
            # engine, handed a promotion diff and no finding to address, invented
            # edits across dhcp/src/*: files this qa->main promotion had no
            # business touching and whose new content existed on neither dev nor
            # qa. That cannot converge, either. Every attempt moves the head,
            # which re-runs the panel, which scores about the same, which
            # remediates again — the PR churns until the attempt ceiling stops
            # it, having drifted further from the source branch each pass.
            #
            # Reviewer uncertainty is not a defect an edit can clear. With no
            # finding and no dissent there is nothing to repair, so leave the
            # branch identical to its source and let the merge gate decide.
            reason = (
                "promotion PR (head '%s') — panel filed no finding and no dissent; a "
                "confidence deficit alone is not something an edit to this branch can "
                "address, so it keeps exactly what the source branch has" % head_ref
            )
        # A reason to skip: record it on the PR and stop.
        if reason:
            logger.info("auto_remediate_pr: %s: %s", key, reason)
            update_pr_review(repo_full_name, pr.number, auto_remediate_blocked=True,
                             auto_remediate_blocked_head=head_sha,
                             auto_remediate_reason=reason,
                             auto_remediate_failure=reason)
            return False, reason

    # Guardrails check
    passed, violation = check_pr_guardrails(pr, files, changed_paths, config)
    # Blocked: build guidance and a banner, post it once, and lock the PR from auto-fixing.
    if not passed:
        guidance = pr_concierge.generate_user_guidance(
            repo_name=repo_full_name,
            pr_number=pr.number,
            violation=violation,
            changed_files=changed_paths,
        )
        banner = (
            "🚨 **AppBuilder — Security Guardrail Violation Detected**\n\n"
            "Automated remediation is strictly blocked because this PR touches security-sensitive invariants or contains potential security risks:\n\n"
            f"- **Violation**: {violation}\n\n"
            "**Action**: This PR has been locked from automated fixes and requires mandatory human review.\n\n"
            f"{guidance}"
        )
        _post_once("guardrail", banner, guardrail_violation=violation,
                   auto_remediate_blocked=True, auto_remediate_blocked_head=head_sha,
                   auto_remediate_reason=f"Guardrail violation: {violation}")
        return False, f"Guardrail violation: {violation}"

    # Attempt ceiling check
    # Attempts so far and the ceiling.
    attempts = rec.get("remediation_attempts", 0)
    max_attempts = int(config.get("pr_auto_remediate_max_attempts", 3))
    # The premium tier buys ONE more turn past the ordinary ceiling, once per
    # PR -- see premium_turn_available. Everything below (the exhausted
    # comment, the human hand-off) still fires when that turn is also spent.
    premium_turn = attempts >= max_attempts and premium_turn_available(rec, config)
    if premium_turn:
        logger.info("auto_remediate_pr: %s — ordinary budget spent (%d/%d); taking the single "
                    "premium escalation attempt", key, attempts, max_attempts)
    # Out of attempts with no premium turn left: post guidance once and hand to a human.
    if attempts >= max_attempts and not premium_turn:
        guidance = pr_concierge.generate_user_guidance(
            repo_name=repo_full_name,
            pr_number=pr.number,
            review_report=rec.get("panel_critique") or rec.get("dissent_feedback"),
            attempts=attempts,
            max_attempts=max_attempts,
            changed_files=changed_paths,
        )
        exhausted_comment = (
            "🤖 **AppBuilder — Automated Remediation Limit Reached**\n\n"
            f"AppBuilder attempted to remediate review findings {attempts} times but was unable to resolve all critiques. Leaving for human review.\n\n"
            f"{guidance}"
        )
        _post_once("exhausted", exhausted_comment,
                   auto_remediate_status="exhausted_human_review",
                   auto_remediate_reason="Remediation attempt limit reached")
        return False, "Remediation attempt limit reached"


    # Twin-parity detection and auto-mirroring on pxmx
    if "pxmx" in repo_full_name.lower():
        # Record each twin file that drifted, with the mirrored content from the source.
        drifts = twin_sync.detect_twin_drift(repo_full_name, files)
        if drifts:
            mirrored_list = []
            for d in drifts:
                src_path = d.get("source")
                tgt_path = d.get("twin")
                src_f = next((f for f in files if getattr(f, "filename", "") == src_path), None)
                src_content = getattr(src_f, "patch", "") if src_f else ""
                mirror_data = twin_sync.mirror_twin_content(src_path, tgt_path, src_content)
                mirrored_list.append(mirror_data)
            rec["mirrored_twins"] = mirrored_list

    # Wire contract & Performance hotpath audits
    # Run the wire-contract and hot-path performance audits.
    contract_warnings = contract_guard.audit_wire_contract(files)
    perf_warnings = perf_auditor.audit_performance_hotpaths(files)
    # NOTE: in the persisted review record (app_state.record_pr_review) "findings"
    # is the finding COUNT (an int) and "items" is the finding LIST. This block
    # used to `rec["findings"].extend(...)`, which raised
    # AttributeError: 'int' object has no attribute 'extend' and aborted
    # remediation for every PR that tripped a contract/perf audit.
    audit_items = list(contract_warnings or []) + list(perf_warnings or [])
    # Add their findings to the review record and bump the matching counts.
    if audit_items:
        merged_items = list(rec.get("items") or [])
        merged_items.extend(audit_items)
        rec["items"] = merged_items
        rec["findings"] = len(merged_items)
        for _w in audit_items:
            _field = _LEVEL_COUNT_FIELD.get((_w.get("level") or "warning").lower())
            if _field:
                rec[_field] = int(rec.get(_field) or 0) + 1

    # Assess complexity & requirements
    # Collect the panel critiques and any dissent feedback (read from the PR if missing).
    critique = "\n".join(c for c in (rec.get("panel_critique"), rec.get("panel2_critique")) if c)
    dissent_feedback = rec.get("dissent_feedback") or ""
    if not dissent_feedback:
        try:
            import pr_review_score
            report, body = pr_review_score.read_pr_review(pr)
            dissent_feedback = pr_review_score.dissent_feedback(report, body).strip()
        except Exception:
            pass

    # "items" (not "findings") is the finding list — see the audit block above.
    findings = rec.get("items") or []
    assessed_complexity = assess_fix_complexity(critique, dissent_feedback, findings, files)

    # A large approval deficit means the panel doubts the change itself, not its
    # spelling. assess_fix_complexity only reads the critique TEXT and the file
    # count, so a one-file diff that both panels flatly denied was being sent to
    # a "small" model — the cheapest model asked to solve the hardest objection.
    # Floor the tier by how far under target the PR actually sits.
    if deficit >= 0.30 and _COMPLEXITY_RANK_ORDER.index(assessed_complexity) < _COMPLEXITY_RANK_ORDER.index("large"):
        assessed_complexity = "large"
    elif deficit >= 0.10 and _COMPLEXITY_RANK_ORDER.index(assessed_complexity) < _COMPLEXITY_RANK_ORDER.index("medium"):
        assessed_complexity = "medium"

    # Requirements class, plus the previous attempt's tier and model.
    from model_selection import LlmRequirements as _ReqClass
    prev_complexity = rec.get("last_remediation_complexity")
    last_tried_model = rec.get("last_remediation_model")

    # A retry: step up from the previous tier and exclude the model that failed.
    if attempts > 0 and prev_complexity:
        prev_reqs = _ReqClass(
            complexity=prev_complexity,
            needs_structured_output=True,
            exclude_models=tuple(rec.get("excluded_models") or []),
        )
        reqs = next_remediation_requirements(prev_reqs, failure_kind="retry", tried_key=last_tried_model, config=config, attempts=attempts, premium=premium_turn)
    # First attempt: apply the premium/cost exclusions only.
    else:
        reqs = next_remediation_requirements(
            _ReqClass(complexity=assessed_complexity, needs_structured_output=True),
            config=config, attempts=attempts, premium=premium_turn)
        # next_remediation_requirements steps the complexity up a rung; on the
        # FIRST attempt there is nothing to step away from, so keep the tier
        # assessed from the diff and take only the premium/cost pool split.
        reqs = _ReqClass(
            complexity=assessed_complexity,
            needs_structured_output=True,
            exclude_models=getattr(reqs, "exclude_models", ()),
        )

    # Invoke fix_one_pr
    # Use fix_one_pr unless a fix function was passed in (e.g. by tests).
    if fix_fn is None:
        from pr_review import fix_one_pr as default_fix_fn
        fix_fn = default_fix_fn

    # Run the fix, catching any failure as an unsuccessful attempt.
    used_model_out: Dict[str, Any] = {}
    try:
        success, msg = fix_fn(
            repo_full_name,
            pr.number,
            config=config,
            requirements=reqs,
            used_model_out=used_model_out,
        )
    except Exception as e:
        success = False
        msg = f"Fix invocation failed: {e}"

    # Which model actually ran.
    used_model = used_model_out.get("model") or used_model_out.get("key")

    # Contention is not an attempt. fix_one_pr bailed on the per-PR lock before
    # selecting a model or touching a checkout, so there is no work to charge
    # and no model to blame -- and charging it anyway burned both the
    # remediation budget and (on an escalation turn) the premium budget on a
    # scan that did nothing. Returned before new_attempts is computed so no
    # counter can be incremented on this path by accident.
    if not success and fix_failures.is_contended_failure(msg):
        update_pr_review(
            repo_full_name,
            pr.number,
            remediation_attempts=attempts,
            auto_remediate_status="contended",
            auto_remediate_failure=msg,
        )
        logger.info(
            "auto_remediate_pr: %s — another fix is already in flight for this PR; "
            "not charged to the remediation budget, retrying next scan", key)
        return False, msg

    # This run counts as one more attempt.
    new_attempts = attempts + 1

    # Charge the premium budget when the premium TURN IS TAKEN, whatever model
    # ended up answering. "turn granted" and "premium call made" used to be
    # computed from two different sources and could silently diverge: when
    # fix_engine._premium_fix_exclusions(want_premium=True) finds no selectable
    # premium model it leaves the pool UNNARROWED (an ordinary model writes the
    # fix), and a fix_fn that fails before a model is recorded leaves
    # used_model None. In both of those states the model-based charge never
    # fired, premium_turn_available() stayed True forever, and the
    # `attempts >= max_attempts and not premium_turn` exhausted/human-review
    # hand-off became unreachable -- an unbounded remediation loop. Charging the
    # turn makes the escalation budget bind in every state. The model-based
    # charge is kept as an additional accounting path, for the case where a
    # premium model answers on an ordinary (non-escalation) turn.
    try:
        import fix_engine as _fe
        _premium_used = int(rec.get("premium_attempts") or 0)
        _premium_charged = False
        if premium_turn:
            _premium_used += 1
            _premium_charged = True
        elif used_model and _fe.is_premium_fix_model(used_model, config):
            _premium_used += 1
            _premium_charged = True
        if _premium_charged:
            logger.info("auto_remediate_pr: %s — premium escalation attempt %d/%d used (%s)",
                        key, _premium_used, _premium_budget(config), used_model or "no model recorded")
    except Exception:  # noqa: BLE001 -- accounting must never break the fix path
        # Fail SAFE for the budget: a bookkeeping error must not hand out an
        # unlimited supply of premium turns.
        _premium_used = int(rec.get("premium_attempts") or 0) + (1 if premium_turn else 0)

    # Success: record the attempt, the tier and the model used.
    if success:
        update_pr_review(
            repo_full_name,
            pr.number,
            remediation_attempts=new_attempts,
            premium_attempts=_premium_used,
            auto_remediate_status="success",
            last_remediation_complexity=reqs.complexity,
            last_remediation_model=used_model,
        )
        logger.info("auto_remediate_pr: remediation succeeded for %s: %s", key, msg)
        return True, msg
    else:
        # A barren reply -- empty, no JSON, unparseable JSON -- tells us nothing
        # about the fix, only that the model failed to speak. Charging it to the
        # remediation budget let three prose replies exhaust all 3 attempts
        # having made zero real fix attempts, and excluding the model on top of
        # that permanently shrank the pool over a fault that was never the
        # model's competence. fix_one_pr already grants these a separate barren
        # allowance; this path never got the same lesson.
        if fix_failures.is_barren_failure(msg):
            barren_done = int(rec.get("remediation_barren") or 0)
            max_barren = max(0, min(
                int(config.get("pr_remediate_max_barren_retries", 2) or 0), 3))
            if barren_done < max_barren:
                update_pr_review(
                    repo_full_name,
                    pr.number,
                    remediation_attempts=attempts,
                    remediation_barren=barren_done + 1,
                    premium_attempts=_premium_used,
                    auto_remediate_status="barren",
                    auto_remediate_failure=msg,
                    last_remediation_complexity=reqs.complexity,
                    last_remediation_model=used_model,
                )
                logger.warning(
                    "auto_remediate_pr: %s barren attempt (%s/%s) not charged to the "
                    "remediation budget: %s", key, barren_done + 1, max_barren, msg)
                return False, msg

        # A real failure: record it and exclude the model that failed from the next try.
        excluded = list(rec.get("excluded_models") or [])
        if used_model and used_model not in excluded:
            excluded.append(used_model)
        update_pr_review(
            repo_full_name,
            pr.number,
            remediation_attempts=new_attempts,
            premium_attempts=_premium_used,
            auto_remediate_status="failed",
            auto_remediate_failure=msg,
            last_remediation_complexity=reqs.complexity,
            last_remediation_model=used_model,
            excluded_models=excluded,
        )
        logger.warning("auto_remediate_pr: remediation failed for %s: %s", key, msg)
        return False, msg


def maybe_auto_remediate(
    gh: Any,
    repo: Any,
    pr: Any,
    config: Optional[Dict[str, Any]] = None,
) -> Tuple[bool, str]:
    """Entry point called from pr_review._review_one when PR is open, not merged,
    and auto-merge did not merge the PR.

    AppBuilder's objective on a PR is to drive its skeptical-panel approval
    score as close to 100% as possible — see should_remediate, which is the
    single place that objective is defined. This function is only the
    containment wrapper around it (kill switch, draft/open/merged, guardrail
    latch, docs policy).

    Every exit records WHY on the review record (auto_remediate_reason) so a
    DENY that AppBuilder chose not to act on is visible in the UI instead of
    being an invisible no-op.
    """
    # Identify the PR.
    config = config or {}
    repo_full_name = getattr(repo, "full_name", str(repo))
    key = f"{repo_full_name}#{pr.number}"

    def _skip(reason, **fields):
        """Record the decision, then refuse. Without this an operator staring at
        a 🔴 DENY review has no way to tell 'AppBuilder decided not to act' from
        'AppBuilder never ran'."""
        # Save the reason on the review record; a save failure is only logged.
        try:
            update_pr_review(repo_full_name, pr.number,
                             auto_remediate_reason=reason, **fields)
        except Exception as e:  # noqa: BLE001 — never let bookkeeping break the scan
            logger.debug("maybe_auto_remediate: could not record skip for %s: %s", key, e)
        return False, reason

    # Skip when remediation is off, or the PR is a draft, merged or closed.
    if not config.get("pr_auto_remediate_enabled", True):
        return False, "pr_auto_remediate_enabled is false"
    if getattr(pr, "draft", False):
        return False, "PR is a draft"
    if getattr(pr, "merged", False):
        return False, "PR is already merged"
    if (getattr(pr, "state", "") or "open").lower() != "open":
        return False, "PR is not open"

    # The PR's review record and current head.
    rec = (state.get("pr_reviews") or {}).get(key) or {}
    head_sha = getattr(getattr(pr, "head", None), "sha", None)

    # Already auto-merged: nothing to do.
    if rec.get("auto_merged"):
        return False, "PR was auto-merged"

    # The guardrail latch is PER-HEAD, not permanent. It used to be a one-way
    # door: a single tripped boundary (or a promotion-branch skip) set
    # auto_remediate_blocked=True forever, so even after the author pushed a
    # commit that no longer touched the boundary at all, AppBuilder refused to
    # look at the PR again for the rest of its life. Re-evaluate on a new head;
    # if the diff still trips a guardrail, auto_remediate_pr re-latches it.
    if rec.get("auto_remediate_blocked"):
        # A record latched BEFORE auto_remediate_blocked_head existed has no
        # stored head at all. Treating that missing value as "same head" (it
        # used to fall into the `in (None, head_sha)` arm) left exactly the
        # records this change was meant to free — the ones already stuck —
        # blocked forever, so the one-way door was only ever removed for
        # latches written afterwards. A latch we cannot attribute to a
        # specific commit is stale by definition: re-evaluate it.
        _blocked_head = rec.get("auto_remediate_blocked_head")
        if head_sha and _blocked_head != head_sha:
            logger.info("maybe_auto_remediate: %s — guardrail block was recorded for %s, "
                        "current head is %s, re-evaluating",
                        key, (_blocked_head or "an unknown head"), head_sha[:8])
            update_pr_review(repo_full_name, pr.number, auto_remediate_blocked=False,
                             auto_remediate_blocked_head=None)
            rec = (state.get("pr_reviews") or {}).get(key) or {}
        else:
            return _skip("PR remediation is blocked by guardrail")
    # Out of attempts: a human has to take over.
    if rec.get("auto_remediate_status") == "exhausted_human_review":
        return _skip("PR remediation attempt limit reached")

    # Documentation PRs are reviewed but not accuracy-gated (same operator
    # policy as pr_review._automerge_decision's docs bypass). Remediation
    # exists to make a PR pass the skeptical panel; for a docs-only diff the
    # panel's accuracy critique is not a gate, so "fixing" it would rewrite
    # the author's prose to satisfy a judgement nothing is waiting on — churn
    # that moves the head SHA, re-triggers the panel and burns tokens.
    # Fails closed: a diff not provably docs-only remediates as before.
    if config.get("pr_auto_remediate_skip_docs_only", True):
        try:
            files = feature_allowlist.files_from_pr_files(pr.get_files())
            verdict = feature_allowlist.classify(files, config.get("feature_automerge_allowlist"))
            if (verdict.get("category") == feature_allowlist.DOCS_ONLY
                    and verdict.get("auto_approvable") is True):
                return _skip("documentation-only PR — reviewed but not accuracy-gated")
        except Exception as e:  # noqa: BLE001
            logger.debug("maybe_auto_remediate: docs-only check skipped for %s: %s", key, e)

    # THE OBJECTIVE. Everything above is containment; this is the actual "is
    # this PR good enough yet?" question, and it is what makes a panel
    # recommendation trigger a repair instead of just being published.
    should, reason, deficit = should_remediate(rec, config)
    if not should:
        return _skip(reason, auto_remediate_deficit=0.0)
    logger.info("maybe_auto_remediate: %s — %s (deficit %.2f)", key, reason, deficit)
    update_pr_review(repo_full_name, pr.number, auto_remediate_reason=reason,
                     auto_remediate_deficit=deficit)

    # Go ahead and remediate.
    return auto_remediate_pr(gh, repo, pr, config, deficit=deficit)

